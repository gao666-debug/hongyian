#ifndef __BOARD_CHECK_H
#define __BOARD_CHECK_H

/* 整板自检：上电跑一次，把板子上每个子系统的「电气状态」打到串口。
 *
 * 分成四段：
 *   1. 引脚占用清单（哪些脚能用、哪些脚是 Flash 取指总线绝对不能碰）
 *   2. 引脚负载检测：每个 LCD 脚分别上拉/下拉后回读，判断是悬空、被拉死还是短路
 *   3. I2C 总线扫描：SCL=IO15 / SDA=IO16，找 0x57(MAX3010x) 与 0x68(MPU6050)
 *   4. LCD 通信检测：硬件复位后用 RDDID(0x04) 读屏的 ID，
 *      逐个候选时钟脚试 —— 只有真正连到屏 SCL 的那一个脚才能读回非 0xFF 的数据。
 *
 * 第 4 段是整块板子上唯一能「程序自己判断屏通没通」的手段：
 * 屏是输入器件，我们发指令它不会回应；只有读寄存器时它才会驱动 SDA，
 * 所以能读回正确 ID = SCL 与 SDA 两根线都通到屏了。
 */
void board_check_run(void);

/* 自检里找到的屏时钟脚（找到则 != -1），UI 层可以直接用 */
extern int g_bc_lcd_clk;

#endif
